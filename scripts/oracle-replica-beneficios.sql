-- Instalación manual como INSUDB, una sola vez, primero en ensayo.
-- Tablas persistentes: NO GLOBAL TEMPORARY. DDL realiza commit implícito.
-- CTAS hereda tipos del destino; no copia triggers ni claves del destino.
CREATE TABLE INSUDB.TEMP_VT_BEN_REPLICA (
 ID VARCHAR2(32 CHAR) NOT NULL,
 PLAN CLOB NOT NULL,
 REVISION VARCHAR2(64 CHAR) NOT NULL,
 ESTADO VARCHAR2(24 CHAR) NOT NULL,
 CREADO DATE DEFAULT SYSDATE NOT NULL,
 FECHA_COPIA DATE NOT NULL,
 BASE_FILAS NUMBER(12) DEFAULT 0 NOT NULL,
 TOTAL NUMBER(15) DEFAULT 0 NOT NULL,
 PREPARADOS NUMBER(15) DEFAULT 0 NOT NULL,
 ELIMINADOS NUMBER(15) DEFAULT 0 NOT NULL,
 ERROR VARCHAR2(2000 CHAR),
 CONSTRAINT PK_VT_BEN_REPLICA PRIMARY KEY(ID),
 CONSTRAINT CK_VT_BEN_ESTADO CHECK(ESTADO IN ('REVISADO','EN_COLA','PREPARANDO','PAUSADO','ERROR','COMPLETADO','RESTAURAR','ERROR_RESTAURAR','RESTAURADO')),
 CONSTRAINT CK_VT_BEN_CONT CHECK(BASE_FILAS>=0 AND TOTAL>=0 AND PREPARADOS>=0 AND PREPARADOS<=TOTAL AND ELIMINADOS>=0)
);
CREATE INDEX INSUDB.IX_VT_BEN_COLA ON INSUDB.TEMP_VT_BEN_REPLICA(ESTADO,CREADO);
CREATE TABLE INSUDB.TEMP_VT_BEN_EVENTO (
 EVENTO_ID VARCHAR2(32 CHAR) NOT NULL,
 ID VARCHAR2(32 CHAR) NOT NULL,
 FECHA DATE DEFAULT SYSDATE NOT NULL,
 ACCION VARCHAR2(30 CHAR) NOT NULL,
 DETALLE VARCHAR2(2000 CHAR),
 CONSTRAINT PK_VT_BEN_EVENTO PRIMARY KEY(EVENTO_ID),
 CONSTRAINT FK_VT_BEN_EVENTO FOREIGN KEY(ID) REFERENCES INSUDB.TEMP_VT_BEN_REPLICA(ID)
);
CREATE INDEX INSUDB.IX_VT_BEN_EVENTO ON INSUDB.TEMP_VT_BEN_EVENTO(ID,FECHA);
CREATE TABLE INSUDB.TEMP_VT_BEN_DESTINO (
 ID VARCHAR2(32 CHAR) NOT NULL,
 NMODULEC NUMBER(10) NOT NULL,
 ORDEN NUMBER(5) NOT NULL,
 ANTERIORES NUMBER(15) NOT NULL,
 CONSTRAINT PK_VT_BEN_DESTINO PRIMARY KEY(ID,NMODULEC),
 CONSTRAINT UK_VT_BEN_ORDEN UNIQUE(ID,ORDEN),
 CONSTRAINT FK_VT_BEN_DESTINO FOREIGN KEY(ID) REFERENCES INSUDB.TEMP_VT_BEN_REPLICA(ID)
);
CREATE TABLE INSUDB.TEMP_VT_BEN_SNAPSHOT AS
 SELECT CAST(NULL AS VARCHAR2(32 CHAR)) ID, CAST(NULL AS VARCHAR2(5 CHAR)) TIPO, CAST(NULL AS NUMBER(15)) ITEM_NO,
 NBRANCH,NPRODUCT,NMODULEC,DEFFECDATE,NCOVER,NROLE,NDED_TYPE,NQUANTITY,NAMOUNT_BENE,NPERCEN_HOSPITAL,NPERCEN_AMBULATORY,SCHANALLO,DNULLDATE,DCOMPDATE,NUSERCODE,SCAREN_TYPE,NCAREN_QUANT,NOFFICE_PROD,NAMOUNT_COPAY,NFRANCFIX,NAGESTART,NAGEEND,SSEXCLIEN,NPROVIDER,NATTENSYSTEM,NTYPEEXHAUS,SILLNESS,SCLARIFICACT,NINDPRINT,NBENEFCATEG,NIDMEDBENEF,SBENEFCATEG_CODE,SPRINT_DES,NORDER
 FROM INSUDB.MEDBENEFITS_PROD WHERE 1=0;
ALTER TABLE INSUDB.TEMP_VT_BEN_SNAPSHOT MODIFY (ID NOT NULL,ITEM_NO NOT NULL,TIPO NOT NULL);
ALTER TABLE INSUDB.TEMP_VT_BEN_SNAPSHOT ADD CONSTRAINT PK_VT_BEN_SNAPSHOT PRIMARY KEY(ID,TIPO,ITEM_NO);
ALTER TABLE INSUDB.TEMP_VT_BEN_SNAPSHOT ADD CONSTRAINT FK_VT_BEN_SNAPSHOT FOREIGN KEY(ID) REFERENCES INSUDB.TEMP_VT_BEN_REPLICA(ID);
ALTER TABLE INSUDB.TEMP_VT_BEN_SNAPSHOT ADD CONSTRAINT CK_VT_BEN_TIPO CHECK(TIPO IN ('BASE','ANTES'));
CREATE TABLE INSUDB.TEMP_VT_BEN_STAGE AS
 SELECT CAST(NULL AS VARCHAR2(32 CHAR)) ID, CAST(NULL AS NUMBER(15)) ITEM_NO,
 NBRANCH,NPRODUCT,NMODULEC,DEFFECDATE,NCOVER,NROLE,NDED_TYPE,NQUANTITY,NAMOUNT_BENE,NPERCEN_HOSPITAL,NPERCEN_AMBULATORY,SCHANALLO,DNULLDATE,DCOMPDATE,NUSERCODE,SCAREN_TYPE,NCAREN_QUANT,NOFFICE_PROD,NAMOUNT_COPAY,NFRANCFIX,NAGESTART,NAGEEND,SSEXCLIEN,NPROVIDER,NATTENSYSTEM,NTYPEEXHAUS,SILLNESS,SCLARIFICACT,NINDPRINT,NBENEFCATEG,NIDMEDBENEF,SBENEFCATEG_CODE,SPRINT_DES,NORDER
 FROM INSUDB.MEDBENEFITS_PROD WHERE 1=0;
ALTER TABLE INSUDB.TEMP_VT_BEN_STAGE MODIFY (ID NOT NULL,ITEM_NO NOT NULL);
ALTER TABLE INSUDB.TEMP_VT_BEN_STAGE ADD CONSTRAINT PK_VT_BEN_STAGE PRIMARY KEY(ID,ITEM_NO);
ALTER TABLE INSUDB.TEMP_VT_BEN_STAGE ADD CONSTRAINT FK_VT_BEN_STAGE FOREIGN KEY(ID) REFERENCES INSUDB.TEMP_VT_BEN_REPLICA(ID);
