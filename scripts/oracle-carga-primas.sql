-- Tablas persistentes de trabajo: no son GLOBAL TEMPORARY TABLE.
-- No cambia ni elimina tarifas existentes. DDL Oracle realiza commit implícito.
CREATE TABLE INSUDB.TEMP_VT_PRIMA_IMPORT (
 ID VARCHAR2(32 CHAR) NOT NULL,
 ARCHIVO VARCHAR2(255 CHAR) NOT NULL,
 HUELLA VARCHAR2(64 CHAR) NOT NULL,
 ESTADO VARCHAR2(20 CHAR) NOT NULL,
 DOCUMENTO CLOB NOT NULL,
 ORIGINAL BLOB NOT NULL,
 PLAN CLOB,
 PLAN_HASH VARCHAR2(64 CHAR),
 CREADO DATE DEFAULT SYSDATE NOT NULL,
 TOTAL NUMBER(12) DEFAULT 0 NOT NULL,
 PREPARADOS NUMBER(12) DEFAULT 0 NOT NULL,
 INSERTADOS NUMBER(12) DEFAULT 0 NOT NULL,
 EXISTENTES NUMBER(12) DEFAULT 0 NOT NULL,
 ERROR VARCHAR2(2000 CHAR),
 CONSTRAINT PK_VT_PRIMA_IMPORT PRIMARY KEY(ID),
 CONSTRAINT CK_VT_PRIMA_ESTADO CHECK(ESTADO IN ('BORRADOR','REVISADO','EN_COLA','PREPARANDO','PAUSADO','ERROR','COMPLETADO')),
 CONSTRAINT CK_VT_PRIMA_CONT CHECK(PREPARADOS>=0 AND PREPARADOS<=TOTAL AND INSERTADOS>=0 AND EXISTENTES>=0 AND INSERTADOS+EXISTENTES<=TOTAL)
);
CREATE INDEX INSUDB.IX_VT_PRIMA_COLA ON INSUDB.TEMP_VT_PRIMA_IMPORT(ESTADO,CREADO);
CREATE TABLE INSUDB.TEMP_VT_PRIMA_STAGE AS
 SELECT CAST(NULL AS VARCHAR2(32 CHAR)) IMPORT_ID, CAST(NULL AS NUMBER(12)) ITEM_NO,
 CAST(NULL AS NUMBER(10)) SOURCE_ROW,
 NBRANCH,NPRODUCT,DEFFECDATE,NROLE,NMODULEC,NCOVER,NGEOGRAPHAREA,NATTENSYSTEM,NOFFICE,
 NCAPITAL_INIT,NCAPITAL_END,NPOLICY_YEAR_INIT,NPOLICY_YEAR_END,NCURRENCY,NAGE_INIT,NAGE_END,
 NAMOUNTF,NAMOUNTM,DNULLDATE,DCOMPDATE,NUSERCODE FROM INSUDB.TAR_HEALT_PREM WHERE 1=0;
ALTER TABLE INSUDB.TEMP_VT_PRIMA_STAGE MODIFY (IMPORT_ID NOT NULL,ITEM_NO NOT NULL,SOURCE_ROW NOT NULL);
ALTER TABLE INSUDB.TEMP_VT_PRIMA_STAGE ADD RESULTADO VARCHAR2(12 CHAR) DEFAULT 'PREPARADO' NOT NULL;
ALTER TABLE INSUDB.TEMP_VT_PRIMA_STAGE ADD CONSTRAINT CK_VT_PRIMA_RESULT CHECK(RESULTADO IN ('PREPARADO','INSERTADO','EXISTENTE'));
ALTER TABLE INSUDB.TEMP_VT_PRIMA_STAGE ADD CONSTRAINT PK_VT_PRIMA_STAGE PRIMARY KEY(IMPORT_ID,ITEM_NO);
ALTER TABLE INSUDB.TEMP_VT_PRIMA_STAGE ADD CONSTRAINT FK_VT_PRIMA_IMPORT FOREIGN KEY(IMPORT_ID) REFERENCES INSUDB.TEMP_VT_PRIMA_IMPORT(ID);
CREATE INDEX INSUDB.IX_VT_PRIMA_CLAVE ON INSUDB.TEMP_VT_PRIMA_STAGE
 (IMPORT_ID,NBRANCH,NPRODUCT,NMODULEC,NCOVER,NROLE,NOFFICE,DEFFECDATE);
